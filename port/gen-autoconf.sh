#!/bin/sh
# Turns port/config.mk into linuxkpi's generated/autoconf.h, and writes its
# utsrelease.h. Haiku's .gitignore skips generated*, so setup.sh runs this.
here=$(cd "$(dirname "$0")" && pwd)
generated=$here/../haiku/src/libs/compat/linuxkpi/include/generated
mkdir -p "$generated"
out=$generated/autoconf.h
{
	echo "/* Generated by port/gen-autoconf.sh from port/config.mk; do not edit. */"
	echo "#ifndef _LINUXKPI_GENERATED_AUTOCONF_H"
	echo "#define _LINUXKPI_GENERATED_AUTOCONF_H"
	sed -n 's/^\(CONFIG_[A-Z0-9_]*\)=y$/#define \1 1/p; s/^\(CONFIG_[A-Z0-9_]*\)=\([0-9][0-9xa-fA-F]*\)$/#define \1 \2/p; s/^\(CONFIG_[A-Z0-9_]*\)=\("[^"]*"\)$/#define \1 \2/p' "$here/config.mk"
	echo "#endif"
} > "$out"

cat > "$generated/utsrelease.h" <<'EOF'
/*
 * Copyright 2026, hans2294.
 * Distributed under the terms of the MIT License.
 */
#ifndef _LINUXKPI_GENERATED_UTSRELEASE_H
#define _LINUXKPI_GENERATED_UTSRELEASE_H

#define UTS_RELEASE "6.12.115-haiku"

#endif
EOF
