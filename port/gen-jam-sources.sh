#!/bin/sh
# Writes the Linux source list of the amdgpu add-on as jam, from
# port/files.txt, with each file's Kbuild module name.
here=$(cd "$(dirname "$0")" && pwd)
out=$here/../haiku/src/add-ons/kernel/drivers/graphics/amdgpu/LinuxSources
{
	echo "# Generated by port/gen-jam-sources.sh from port/files.txt; do not edit."
	echo "# Pairs of <path in linux-6.12> <KBUILD_MODNAME>."
	echo "LINUX_SOURCES ="
	while read -r f; do
		dir=$(dirname "$f")
		case $dir in
			drivers/gpu/drm/amd/*) m=amdgpu ;;
			drivers/gpu/drm/ttm) m=ttm ;;
			drivers/gpu/drm/scheduler) m=gpu_sched ;;
			drivers/gpu/drm/display) m=drm_display_helper ;;
			drivers/dma-buf) m=dma_buf ;;
			lib|drivers/gpu|drivers/video|drivers/i2c/*) m=linuxkpi_lib ;;
			*) m=drm ;;
		esac
		echo "	$f $m"
	done < "$here/files.txt"
	echo "	;"
} > "$out"
